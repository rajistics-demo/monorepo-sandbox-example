#!/usr/bin/env python3
"""Materialize the synthetic settlement corpus locally, verified against the manifest (stdlib only).

  materialize.py [--dest DIR] [--only 2025-03-14,...] [--only-from-tests server/test] [--shard K]
                 [--budget-root DIR --budget-bytes N] [--min-node-free-bytes N] [--jobs N]
                 [--report out.json] [--verify-only | --check-only]

Every day is regenerated from generate.py (deterministic, no network) and must
match the size and sha256 that the committed server/data/settlements/manifest.json
pins for it. Nothing is downloaded.

  default        write each missing day to a hidden .part file, check it, then rename
                 it read-only. A mismatch deletes the partial file and fails (exit 4).
  --verify-only  re-hash files already present; generate nothing.
  --check-only   generate each selected day in memory and compare it with the
                 manifest; write nothing. Use this to prove the full corpus
                 reproduces without needing ~9.6 GB of disk.

Selection: all 731 days by default; --only, --only-from-tests (days named in *.rb
files) and --shard K (calendar quarter K of 8) narrow it.

Disk gates (exit 3, checked before anything is written and after every file):
  --min-node-free-bytes  free bytes on the destination filesystem must stay above this floor.
  --budget-root/--budget-bytes  allocated bytes under the root plus this run's planned
      writes must stay within the budget.

Exit codes: 0 ok, 2 usage/manifest error, 3 disk gate, 4 verification failure.
"""
import argparse
import hashlib
import json
import os
import re
import sys
import time
from concurrent.futures import ProcessPoolExecutor
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import generate  # noqa: E402

CHUNK = 1 << 20
DATE_RE = re.compile(r"\b(20(?:24|25)-(?:0[1-9]|1[0-2])-(?:0[1-9]|[12]\d|3[01]))\b")
DATE_NEW_RE = re.compile(r"Date\.new\(\s*(20(?:24|25))\s*,\s*(\d{1,2})\s*,\s*(\d{1,2})\s*\)")


class Gate(Exception):
    code = 3


class Verify(Exception):
    code = 4


def allocated(root: Path) -> int:
    total = 0
    for dirpath, dirnames, filenames in os.walk(root, onerror=lambda e: None):
        for name in filenames + dirnames:
            try:
                total += os.lstat(os.path.join(dirpath, name)).st_blocks * 512
            except OSError:
                pass
    return total


def node_free(path: Path) -> int:
    st = os.statvfs(path)
    return st.f_bavail * st.f_frsize


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(CHUNK), b""):
            h.update(chunk)
    return h.hexdigest()


def present_ok(path: Path, entry, deep: bool) -> bool:
    try:
        if path.stat().st_size != entry["bytes"]:
            return False
    except FileNotFoundError:
        return False
    return sha256_file(path) == entry["sha256"] if deep else True


def wanted_days(args, manifest):
    all_days = [f["settled_on"] for f in manifest["files"]]
    picked = set(all_days)
    if args.only:
        picked &= set(args.only.split(","))
    if args.only_from_tests:
        found = set()
        for p in Path(args.only_from_tests).rglob("*.rb"):
            text = p.read_text(errors="ignore")
            found |= set(DATE_RE.findall(text))
            found |= {f"{y}-{int(m):02d}-{int(d):02d}" for y, m, d in DATE_NEW_RE.findall(text)}
        if not found & set(all_days):
            raise Gate(f"--only-from-tests found no settlement days under {args.only_from_tests}")
        picked &= found
    if args.shard:
        picked &= {d.isoformat() for d in generate.shard_days(args.shard)}
    return picked


def check_day(entry):
    """Generate one day in memory; return (path, ok, bytes, sha256, seconds)."""
    t0 = time.monotonic()
    data, _ = generate.generate_day(date.fromisoformat(entry["settled_on"]))
    digest = hashlib.sha256(data).hexdigest()
    ok = len(data) == entry["bytes"] and digest == entry["sha256"]
    return entry["path"], ok, len(data), digest, round(time.monotonic() - t0, 3)


def write_day(entry, dest: Path):
    final = dest / entry["path"]
    final.parent.mkdir(parents=True, exist_ok=True)
    part = final.with_name("." + final.name + ".part")
    data, _ = generate.generate_day(date.fromisoformat(entry["settled_on"]))
    if len(data) != entry["bytes"] or hashlib.sha256(data).hexdigest() != entry["sha256"]:
        raise Verify(f"{entry['path']}: generated bytes do not match the manifest")
    try:
        with open(part, "wb") as out:
            out.write(data)
        if final.exists():
            final.chmod(0o644)
        os.replace(part, final)
        final.chmod(0o444)
    finally:
        part.unlink(missing_ok=True)
    return final


def du_pair(root: Path):
    logical = alloc = files = 0
    for p in root.rglob("*.csv"):
        st = p.stat()
        logical += st.st_size
        alloc += st.st_blocks * 512
        files += 1
    return {"files": files, "logical_bytes": logical, "allocated_bytes": alloc}


def main():
    here = Path(__file__).resolve().parents[2]
    ap = argparse.ArgumentParser()
    ap.add_argument("--dest", default=str(here / "server/data/settlements"))
    ap.add_argument("--manifest", default=str(here / "server/data/settlements/manifest.json"))
    ap.add_argument("--only", help="comma-separated settlement days")
    ap.add_argument("--only-from-tests", help="only days referenced by *.rb files under this dir")
    ap.add_argument("--shard", type=int, choices=range(1, generate.SHARDS + 1), help="calendar quarter 1..8")
    ap.add_argument("--budget-root")
    ap.add_argument("--budget-bytes", type=int)
    ap.add_argument("--min-node-free-bytes", type=int, default=2 * 10**9)
    ap.add_argument("--jobs", type=int, default=1)
    ap.add_argument("--report")
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--verify-only", action="store_true")
    mode.add_argument("--check-only", action="store_true")
    args = ap.parse_args()
    if bool(args.budget_root) != bool(args.budget_bytes):
        ap.error("--budget-root and --budget-bytes go together")

    manifest_bytes = Path(args.manifest).read_bytes()
    manifest = json.loads(manifest_bytes)
    if manifest.get("schema") != generate.SCHEMA:
        print(f"FAIL manifest schema {manifest.get('schema')!r} != generator {generate.SCHEMA!r}", file=sys.stderr)
        return 2
    entries = {f["path"]: f for f in manifest["files"]}
    dest = Path(args.dest)
    gen_sha = hashlib.sha256(Path(generate.__file__).read_bytes()).hexdigest()
    report = {"schema": manifest["schema"], "manifest_sha256": hashlib.sha256(manifest_bytes).hexdigest(),
              "generator_sha256": gen_sha, "generator_matches_manifest": gen_sha == manifest.get("generator_sha256"),
              "mode": "check-only" if args.check_only else "verify-only" if args.verify_only else "write",
              "dest": None if args.check_only else str(dest), "started_unix": time.time()}
    t0 = time.monotonic()
    try:
        days = wanted_days(args, manifest)
        selected = sorted((e for e in entries.values() if e["settled_on"] in days), key=lambda e: e["settled_on"])
        if not selected:
            raise Gate("no settlement days selected")
        report["days_requested"] = len(selected)
        report["bytes_requested"] = sum(e["bytes"] for e in selected)
        if args.check_only:
            with ProcessPoolExecutor(max_workers=max(1, args.jobs)) as pool:
                results = list(pool.map(check_day, selected, chunksize=1))
            bad = [r[0] for r in results if not r[1]]
            report["check_only"] = {"checked": len(results), "bytes_generated": sum(r[2] for r in results),
                                    "bad_count": len(bad), "bad": bad[:20],
                                    "max_day_seconds": max((r[4] for r in results), default=0)}
            if bad:
                raise Verify(f"{len(bad)} generated day(s) do not match the manifest, first {bad[0]}")
        elif args.verify_only:
            bad = [e["path"] for e in selected if not present_ok(dest / e["path"], e, deep=True)]
            report["verify_only"] = {"checked": len(selected), "bad_count": len(bad), "bad": bad[:20]}
            if bad:
                raise Verify(f"{len(bad)} file(s) missing or not matching the manifest, first {bad[0]}")
        else:
            dest.mkdir(parents=True, exist_ok=True)
            missing = [e for e in selected if not present_ok(dest / e["path"], e, deep=False)]
            planned_alloc = sum(-(-e["bytes"] // 4096) * 4096 for e in missing)
            free = node_free(dest)
            report["gates"] = {"planned_bytes": sum(e["bytes"] for e in missing), "planned_allocated_bytes": planned_alloc,
                               "node_free_before": free, "node_floor": args.min_node_free_bytes}
            if free - planned_alloc < args.min_node_free_bytes:
                raise Gate(f"node free {free} - planned {planned_alloc} < floor {args.min_node_free_bytes}")
            if args.budget_root:
                used = allocated(Path(args.budget_root))
                report["gates"] |= {"budget_root": args.budget_root, "budget_bytes": args.budget_bytes,
                                    "budget_used_before": used}
                if used + planned_alloc > args.budget_bytes:
                    raise Gate(f"budget: used {used} + planned {planned_alloc} > {args.budget_bytes}")
            written = []
            try:
                for e in missing:
                    written.append(write_day(e, dest))
                    if node_free(dest) < args.min_node_free_bytes:
                        raise Gate(f"node free space fell below floor after {e['path']}")
            except BaseException:
                for p in written:
                    p.chmod(0o644)
                    p.unlink(missing_ok=True)
                raise
            report["files_written"] = len(written)
            report["node_free_after"] = node_free(dest)
            if args.budget_root:
                report["budget_used_after"] = allocated(Path(args.budget_root))
            report["dest_csv"] = du_pair(dest)
        report["status"] = "OK"
        rc = 0
    except (Gate, Verify) as e:
        report["status"], report["error"] = type(e).__name__.upper(), str(e)
        print(f"FAIL {report['status']}: {e}", file=sys.stderr)
        rc = e.code
    report["seconds"] = round(time.monotonic() - t0, 3)
    if args.report:
        Path(args.report).parent.mkdir(parents=True, exist_ok=True)
        Path(args.report).write_text(json.dumps(report, indent=1) + "\n")
    print(json.dumps({k: report[k] for k in ("status", "mode", "seconds", "days_requested", "bytes_requested",
                                             "generator_matches_manifest", "dest_csv", "check_only")
                      if k in report}))
    return rc


if __name__ == "__main__":
    sys.exit(main())
